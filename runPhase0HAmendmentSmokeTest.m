function report = runPhase0HAmendmentSmokeTest(outputFolder)
%RUNPHASE0HAMENDMENTSMOKETEST Tiny non-formal execution/resume validation.

arguments
    outputFolder (1,1) string = ""
end
projectFolder=string(fileparts(mfilename("fullpath")));
if strlength(outputFolder)==0
    stamp=string(datetime("now","Format","yyyyMMdd_HHmmss_SSS"));
    outputFolder=fullfile(string(tempdir), ...
        "phase0h_amendment_smoke_"+stamp);
end
formalFolder=fullfile(projectFolder,"results","phase0h_formal_v1_0_0");
integrityBefore=xpsh.formalRunIntegritySnapshot(formalFolder);
plan=smokePlan(xpsh.buildAmendmentPlan(projectFolder));
figureCountBefore=numel(findall(groot,"Type","figure"));
manifest=xpsh.prepareAmendmentRun(plan,outputFolder,projectFolder, ...
    "amendment_smoke","start");
options=struct("MaxNewTrials",2,"TrialExecutor",@xpsh.executeTrial, ...
    "Plotting",struct("enabled",false));
first=xpsh.executePlan(plan,outputFolder,projectFolder,manifest,options);

firstFolder=fullfile(outputFolder,"checkpoints",plan.cells(1).cell_key);
protected=[fullfile(firstFolder,"trial_0001.mat"); ...
    fullfile(firstFolder,"trial_0002.mat"); ...
    fullfile(firstFolder,"cell_complete.mat")];
hashBefore=arrayfun(@(i)xpsh.sha256File(protected(i)), ...
    (1:numel(protected)).');
manifest=xpsh.prepareAmendmentRun(plan,outputFolder,projectFolder, ...
    "amendment_smoke","resume");
options.MaxNewTrials=Inf;
second=xpsh.executePlan(plan,outputFolder,projectFolder,manifest,options);
hashAfter=arrayfun(@(i)xpsh.sha256File(protected(i)), ...
    (1:numel(protected)).');
third=xpsh.executePlan(plan,outputFolder,projectFolder,manifest,options);
status=xpsh.inspectRun(plan,outputFolder,manifest,string(manifest.run_fingerprint));
figureCountAfter=numel(findall(groot,"Type","figure"));
optimizerCalls=countOptimizerCalls(outputFolder,plan,manifest);
integrityAfter=xpsh.formalRunIntegritySnapshot(formalFolder);
checks=struct( ...
    "separate_temporary_output",~contains(outputFolder,"phase0h_formal_v1_0_0"), ...
    "nonformal_seed_namespace",all([plan.cells.family_id]>16), ...
    "optimizer_invocations_exact",optimizerCalls==4, ...
    "composition_only_optimizer_calls_zero",family12CallsAreZero(outputFolder,plan), ...
    "resume_preserved_completed_checkpoints",isequal(hashBefore,hashAfter), ...
    "completed_trials_not_rerun",third.new_trials_executed==0, ...
    "all_smoke_cells_complete",status.run_status=="complete", ...
    "no_figure_increase",figureCountAfter==figureCountBefore, ...
    "plotting_disabled",~first.plotting_enabled && ~second.plotting_enabled, ...
    "original_formal_run_unchanged",isequaln(integrityBefore,integrityAfter));
passed=all(cell2mat(struct2cell(checks)));
report=struct("report_id","phase0h_amendment_smoke_v1_0_1", ...
    "passed",passed,"include_in_amendment_statistics",false, ...
    "output_folder",outputFolder,"plan",plan,"manifest",manifest, ...
    "first_pass",first,"resume_pass",second,"completed_resume_pass",third, ...
    "status",status,"optimizer_invocations",optimizerCalls, ...
    "checks",checks,"original_formal_integrity",integrityAfter);
save(fullfile(outputFolder,"amendment_smoke_report.mat"),"report","-v7");
xpsh.writeJsonAtomic(fullfile(outputFolder,"amendment_smoke_report.json"), ...
    struct("report_id",report.report_id,"passed",passed, ...
    "include_in_amendment_statistics",false,"checks",checks, ...
    "optimizer_invocations",optimizerCalls,"output_folder",outputFolder));
if ~passed
    error("runPhase0HAmendmentSmokeTest:ValidationFailed", ...
        "One or more amendment smoke checks failed.");
end
fprintf("Phase 0H amendment smoke PASSED: %d cells, %d trials, %d " + ...
    "optimizer calls, no figure increase. Output: %s\n", ...
    plan.cell_count,plan.initial_trial_count,optimizerCalls,outputFolder);
end

function plan=smokePlan(base)
charging=base.cells(string({base.cells.cell_key})=="F10_G2");
family12=base.cells(string({base.cells.cell_key})=="F12_R3");
charging.family_id=33;charging.family_name="AmendmentSmokeCharging";
charging.cell_index=1;charging.cell_id="S1";charging.cell_key="AMEND_SMOKE_S1";
charging.trials=2;
family12.family_id=34;family12.family_name="AmendmentSmokeComposition";
family12.cell_index=1;family12.cell_id="S2";family12.cell_key="AMEND_SMOKE_S2";
family12.trials=2;
plan=base;plan.cells=[charging;family12];plan.cell_count=2;
plan.trials_per_cell=2;plan.initial_trial_count=4;
plan.expected_optimizer_invocations=4;
plan.affected_cell_keys=string({plan.cells.cell_key}).';
plan.seed_policy="Smoke-only family IDs 33/34; excluded from amendment statistics.";
plan.optimizer_count_definition= ...
    "Smoke-only: two charging trials with two regional fits each and two " + ...
    "composition-only trials with zero optimizer calls.";
end

function count=countOptimizerCalls(outputFolder,plan,manifest)
count=0;root=fullfile(outputFolder,"checkpoints");
for c=1:numel(plan.cells)
    ids=xpsh.completedTrials(root,string(manifest.run_fingerprint), ...
        string(plan.cells(c).cell_key));
    for id=ids.'
        value=load(fullfile(root,plan.cells(c).cell_key, ...
            compose("trial_%04d.mat",id)),"payload");
        count=count+value.payload.optimizer_invocations;
    end
end
end

function passed=family12CallsAreZero(outputFolder,plan)
cellDef=plan.cells(2);root=fullfile(outputFolder,"checkpoints",cellDef.cell_key);
passed=true;
for id=1:cellDef.trials
    value=load(fullfile(root,compose("trial_%04d.mat",id)),"payload");
    passed=passed && value.payload.optimizer_invocations==0 && ...
        string(value.payload.status)=="success";
end
end
