function report = runSampleABenchmark(backgroundMethod)
%RUNSAMPLEABENCHMARK Standardized exploratory C1s+F1s Sample A report.
%
% This runner does not tune bounds, sensitivity factors, peak count,
% background parameters, or peak definitions against Sample A references.
% Its optional background argument is an explicit local diagnostic choice;
% the versioned JSON default remains unchanged.

arguments
    backgroundMethod (1,1) string = "linear"
end

supported = ["linear", "shirley", "asls", "tougaard"];
backgroundMethod = lower(backgroundMethod);
if ~ismember(backgroundMethod, supported)
    error("runSampleABenchmark:UnsupportedBackground", ...
        "Background must be one of: %s.", strjoin(supported, ", "));
end

projectFolder = fileparts(mfilename("fullpath"));
configFile = fullfile(projectFolder, "config", "legacy_current_v1.json");
referenceFile = fullfile(projectFolder, "reference", ...
    "sample_A_ruoff_v1.json");
c1sFile = fullfile(projectFolder, "C1s_A.txt");
f1sFile = fullfile(projectFolder, "F1s_A.txt");

cfg = jsondecode(fileread(configFile));
cfg.preprocessing.background = backgroundMethod; % local, explicit override

% Production chain. Reference data are intentionally loaded only after
% fitting so they cannot become optimizer inputs.
C = xps.readSpectrum(c1sFile);
F = xps.readSpectrum(f1sFile);
Cpre = xps.preprocessSpectrum(C, cfg.preprocessing);
Fpre = xps.preprocessSpectrum(F, cfg.preprocessing);
Cfit = xps.fitSpectrum(Cpre.energy, Cpre.y_fit, cfg.C1s, ...
    string(cfg.peak_shape));
Ffit = xps.fitSpectrum(Fpre.energy, Fpre.y_fit, cfg.F1s, ...
    string(cfg.peak_shape));
Ffit.peaks = xps.classifyF1sPeaks(Ffit.peaks, ...
    cfg.F1s.classification_boundaries_eV);

scaling = xps.buildQuantificationScaling(Cpre, Fpre, ...
    cfg.acquisition_scaling);
comp = xps.calculateComposition(Cfit.peaks, Ffit.peaks, ...
    cfg.sensitivity_factors.C1s, cfg.sensitivity_factors.F1s, ...
    cfg.composition.alpha_ambiguous, scaling);

reference = xps.loadReference(referenceFile);
referencePeaks = asStructArray( ...
    reference.direct_references.C1s_normal_emission.peaks);

[c1sPeakTable, referenceFractions] = makeC1sPeakTable( ...
    Cfit, Cpre, scaling.C1s, referencePeaks);
f1sPeakTable = makeF1sPeakTable(Ffit, Fpre, scaling.F1s);
fitMetricsTable = makeFitMetricsTable(Cfit, Ffit);
residualSummaryTable = makeResidualSummaryTable(Cfit, Ffit);
C1sResiduals = residualTable(Cfit);
F1sResiduals = residualTable(Ffit);

alpha = cfg.composition.alpha_ambiguous;
derivedReference = deriveC1sReferenceModels(referencePeaks, alpha);
c1sModelComparison = makeC1sModelComparison(comp, derivedReference, alpha);
directReferenceComparison = makeDirectReferenceComparison(comp, ...
    reference.direct_references.overall_sample_A.fluorine_atomic_percent);
scalingTable = makeScalingTable(Cpre, Fpre, scaling);

fprintf("========================================================================\n");
fprintf("  SAMPLE A EXPLORATORY BENCHMARK - CURRENT PRODUCTION PIPELINE\n");
fprintf("========================================================================\n");
fprintf("Diagnostic only: no parameter is tuned against Sample A references.\n");
fprintf("Production chain: read -> preprocess -> fit -> classify -> composition\n");
fprintf("C1s input: %s (%d points; original order %s)\n", c1sFile, ...
    numel(C.energy), directionText(C.energyDirection));
fprintf("F1s input: %s (%d points; original order %s)\n\n", f1sFile, ...
    numel(F.energy), directionText(F.energyDirection));

fprintf("===== Explicit preprocessing =====\n");
fprintf("Normalization: %s\n", Cpre.normalization_method);
fprintf("Requested background: %s\n", backgroundMethod);
fprintf("C1s effective background parameters:\n");
disp(Cpre.background_parameters);
fprintf("F1s effective background parameters:\n");
disp(Fpre.background_parameters);
fprintf("C1s background range: [%.6g, %.6g]\n", ...
    min(Cpre.background), max(Cpre.background));
fprintf("F1s background range: [%.6g, %.6g]\n\n", ...
    min(Fpre.background), max(Fpre.background));

fprintf("===== Normalization and acquisition scaling =====\n");
disp(scalingTable);
fprintf("Scaling status: %s\n", comp.crossRegionAreaScaleStatus);
fprintf("Sensitivity factors (separate from both scales): SC=%.6g, SF=%.6g\n\n", ...
    cfg.sensitivity_factors.C1s, cfg.sensitivity_factors.F1s);

fprintf("===== C1s fitted components and direct Ruoff peak references =====\n");
disp(c1sPeakTable);
fprintf("===== F1s fitted components and position-based classification =====\n");
disp(f1sPeakTable);
fprintf("===== Fit metrics =====\n");
disp(fitMetricsTable);
fprintf("===== Residual summaries (full vectors are saved in the report) =====\n");
disp(residualSummaryTable);

fprintf("===== C1s calculation models vs values derived from Ruoff fractions =====\n");
fprintf("Weighted-model alpha = %.6g\n", alpha);
disp(c1sModelComparison);

overallRef = reference.direct_references.overall_sample_A;
fprintf("===== Direct overall Ruoff references =====\n");
fprintf("Direct fluorine reference: %.3f at.%% F\n", ...
    overallRef.fluorine_atomic_percent);
fprintf("Direct qualitative/stoichiometric reference: %s\n", ...
    string(overallRef.qualitative_stoichiometry));
fprintf("These direct references are distinct from model-derived C1s values.\n");
disp(directReferenceComparison);

if comp.crossRegionValid
    fprintf("C-bound C1s/F1s F/C=%.6g, F at.%%=%.4f, %s\n", ...
        comp.carbonBound.F_over_C, comp.carbonBound.F_atpct, ...
        comp.carbonBound.CxF);
    fprintf("Total-F C1s/F1s F/C=%.6g, F at.%%=%.4f, %s\n", ...
        comp.totalF.F_over_C, comp.totalF.F_atpct, comp.totalF.CxF);
else
    fprintf("C-bound and total-F cross-region results WITHHELD.\n");
    fprintf("Reason: %s\n", comp.crossRegionAreaScaleStatus);
end

printWarnings("C1s", Cfit.warnings);
printWarnings("F1s", Ffit.warnings);

metadata = struct( ...
    "sampleID", "A", ...
    "diagnosticOnly", true, ...
    "backgroundMethod", backgroundMethod, ...
    "configFile", string(configFile), ...
    "configProfile", string(cfg.profile_name), ...
    "configVersion", string(cfg.profile_version), ...
    "referenceFile", string(referenceFile), ...
    "MATLABVersion", string(version), ...
    "generatedAt", datetime("now"));

report = struct( ...
    "metadata", metadata, "configuration", cfg, "reference", reference, ...
    "referenceDerivedFromC1sFractions", derivedReference, ...
    "C", C, "F", F, "Cpre", Cpre, "Fpre", Fpre, ...
    "Cfit", Cfit, "Ffit", Ffit, "scaling", scaling, ...
    "composition", comp, "C1sPeakTable", c1sPeakTable, ...
    "F1sPeakTable", f1sPeakTable, "fitMetricsTable", fitMetricsTable, ...
    "residualSummaryTable", residualSummaryTable, ...
    "C1sResiduals", C1sResiduals, "F1sResiduals", F1sResiduals, ...
    "C1sModelComparison", c1sModelComparison, ...
    "directReferenceComparison", directReferenceComparison, ...
    "scalingTable", scalingTable, ...
    "referenceFractions_pct", referenceFractions);

resultsFolder = fullfile(projectFolder, "results");
if ~exist(resultsFolder, "dir"), mkdir(resultsFolder); end
resultFile = fullfile(resultsFolder, sprintf( ...
    "Sample_A_benchmark_%s_exploratory.mat", char(backgroundMethod)));
save(resultFile, "report");
fprintf("\nSaved %s\n", resultFile);

xps.plotFitComponents(Cpre, Cfit, ...
    "C 1s - Sample A (" + backgroundMethod + "; exploratory)");
xps.plotFitComponents(Fpre, Ffit, ...
    "F 1s - Sample A (" + backgroundMethod + "; exploratory)");
end

function [T, truthFractions] = makeC1sPeakTable(fit, pre, scaling, refs)
n = numel(fit.peaks);
truthCenters = zeros(n,1);
truthFractions = zeros(n,1);
for i = 1:n
    idx = find(string({refs.id}) == fit.peaks(i).id, 1);
    if isempty(idx)
        error("runSampleABenchmark:MissingReferencePeak", ...
            "No Sample A reference exists for peak '%s'.", fit.peaks(i).id);
    end
    truthCenters(i) = refs(idx).center_eV;
    truthFractions(i) = refs(idx).fraction_percent;
end

fitAreas = [fit.peaks.area].';
fitFractions = 100*fitAreas/sum(fitAreas);
recordedAreas = fitAreas*pre.softwareNormalizationScale;
physicalAreas = recordedAreas;
if scaling.acquisitionScaleKnown
    physicalAreas = physicalAreas/scaling.acquisitionScale;
else
    physicalAreas(:) = NaN;
end

T = table(string({fit.peaks.id}).', string({fit.peaks.assignment}).', ...
    [fit.peaks.center_eV].', truthCenters, ...
    [fit.peaks.center_eV].'-truthCenters, [fit.peaks.FWHM_eV].', ...
    fitAreas, recordedAreas, physicalAreas, fitFractions, truthFractions, ...
    fitFractions-truthFractions, ...
    100*(fitFractions-truthFractions)./truthFractions, ...
    [fit.peaks.center_at_bound].', [fit.peaks.FWHM_at_bound].', ...
    [fit.peaks.area_at_bound].', [fit.peaks.center_near_bound].', ...
    [fit.peaks.FWHM_near_bound].', [fit.peaks.area_near_bound].', ...
    'VariableNames', {'ID','Assignment','FitCenter_eV','RuoffCenter_eV', ...
    'CenterError_eV','FWHM_eV','FitArea_normalized','RecordedRawArea', ...
    'PhysicalArea','FitFraction_pct','RuoffFraction_pct', ...
    'FractionError_pp','RelativeFractionError_pct','CenterAtBound', ...
    'FWHMAtBound','AreaAtBound','CenterNearBound','FWHMNearBound', ...
    'AreaNearBound'});
end

function T = makeF1sPeakTable(fit, pre, scaling)
fitAreas = [fit.peaks.area].';
recordedAreas = fitAreas*pre.softwareNormalizationScale;
physicalAreas = recordedAreas;
if scaling.acquisitionScaleKnown
    physicalAreas = physicalAreas/scaling.acquisitionScale;
else
    physicalAreas(:) = NaN;
end
T = table(string({fit.peaks.id}).', string({fit.peaks.assignment}).', ...
    string({fit.peaks.chemical_assignment}).', [fit.peaks.center_eV].', ...
    [fit.peaks.FWHM_eV].', fitAreas, recordedAreas, physicalAreas, ...
    100*fitAreas/sum(fitAreas), ...
    [fit.peaks.include_in_carbon_bound_F].', ...
    [fit.peaks.include_in_total_F].', ...
    [fit.peaks.classification_warning].', ...
    [fit.peaks.center_at_bound].', [fit.peaks.FWHM_at_bound].', ...
    [fit.peaks.area_at_bound].', [fit.peaks.center_near_bound].', ...
    [fit.peaks.FWHM_near_bound].', [fit.peaks.area_near_bound].', ...
    'VariableNames', {'ID','ConfigAssignment','ChemicalClassification', ...
    'FitCenter_eV','FWHM_eV','FitArea_normalized','RecordedRawArea', ...
    'PhysicalArea','FitFraction_pct','IncludeInCarbonBoundF', ...
    'IncludeInTotalF','ClassificationWarning','CenterAtBound', ...
    'FWHMAtBound','AreaAtBound','CenterNearBound','FWHMNearBound', ...
    'AreaNearBound'});
end

function T = makeFitMetricsTable(Cfit,Ffit)
T = table(["C1s";"F1s"], ...
    [Cfit.metrics.RMSE;Ffit.metrics.RMSE], ...
    [Cfit.metrics.R2;Ffit.metrics.R2], ...
    [Cfit.metrics.AICc;Ffit.metrics.AICc], ...
    [Cfit.metrics.BIC;Ffit.metrics.BIC], ...
    [Cfit.exitflag>0;Ffit.exitflag>0], ...
    [Cfit.exitflag;Ffit.exitflag], ...
    'VariableNames', {'Region','RMSE','R2','AICc','BIC', ...
    'Converged','ExitFlag'});
end

function T = makeResidualSummaryTable(Cfit,Ffit)
T = table(["C1s";"F1s"], ...
    [min(Cfit.residual);min(Ffit.residual)], ...
    [max(Cfit.residual);max(Ffit.residual)], ...
    [mean(Cfit.residual);mean(Ffit.residual)], ...
    [std(Cfit.residual);std(Ffit.residual)], ...
    'VariableNames', {'Region','Minimum','Maximum','Mean','StdDev'});
end

function T = residualTable(fit)
T = table(fit.energy, fit.observed, fit.fitted, fit.residual, ...
    'VariableNames', {'BindingEnergy_eV','ObservedBackgroundSubtracted', ...
    'Fitted','Residual'});
end

function derived = deriveC1sReferenceModels(refs, alpha)
ids = string({refs.id});
fractions = [refs.fraction_percent]/100;
area = @(id) fractions(ids==id);
total = sum(fractions);
legacyFC = ((total-area("sp2_C_C"))/total)/3;
weightedFC = (area("C_F") + alpha*area("C_CF23_C_O") + ...
    2*area("CF2") + 3*area("CF3"))/total;
derived = struct("provenance", ...
    "derived by applying project calculation models to direct Ruoff C1s fractions", ...
    "alpha_ambiguous", alpha, "legacy", ratioFields(legacyFC), ...
    "weighted", ratioFields(weightedFC));
end

function T = makeC1sModelComparison(comp, derived, alpha)
derivedFC = [derived.legacy.F_over_C;derived.weighted.F_over_C];
fittedFC = [comp.legacy.F_over_C;comp.weighted.F_over_C];
derivedAt = [derived.legacy.F_atpct;derived.weighted.F_atpct];
fittedAt = [comp.legacy.F_atpct;comp.weighted.F_atpct];
T = table(["Legacy C1s";"Weighted C1s"], [NaN;alpha], ...
    derivedFC, fittedFC, fittedFC-derivedFC, ...
    100*(fittedFC-derivedFC)./derivedFC, derivedAt, fittedAt, ...
    fittedAt-derivedAt, ...
    [derived.legacy.C_over_F;derived.weighted.C_over_F], ...
    [comp.legacy.C_over_F;comp.weighted.C_over_F], ...
    [derived.legacy.CxF;derived.weighted.CxF], ...
    [comp.legacy.CxF;comp.weighted.CxF], ...
    'VariableNames', {'Model','Alpha','DerivedRuoff_F_over_C', ...
    'Fitted_F_over_C','F_over_C_Error','F_over_C_Error_pct', ...
    'DerivedRuoff_F_atpct','Fitted_F_atpct','F_atpct_Error_pp', ...
    'DerivedRuoff_C_over_F','Fitted_C_over_F', ...
    'DerivedRuoff_CxF','Fitted_CxF'});
end

function T = makeDirectReferenceComparison(comp, ruoffAtPct)
models = ["Legacy C1s";"Weighted C1s"];
predicted = [comp.legacy.F_atpct;comp.weighted.F_atpct];
if comp.crossRegionValid
    models = [models;"C-bound C1s/F1s";"Total-F C1s/F1s"];
    predicted = [predicted;comp.carbonBound.F_atpct;comp.totalF.F_atpct];
end
truth = repmat(ruoffAtPct,size(predicted));
T = table(models,truth,predicted,predicted-truth, ...
    100*(predicted-truth)./truth, ...
    'VariableNames', {'Prediction','DirectRuoff_F_atpct', ...
    'Predicted_F_atpct','Error_pp','RelativeError_pct'});
end

function T = makeScalingTable(Cpre,Fpre,scaling)
T = table(["C1s";"F1s"], ...
    [Cpre.normalization_method;Fpre.normalization_method], ...
    [Cpre.softwareNormalizationScale;Fpre.softwareNormalizationScale], ...
    [scaling.C1s.acquisitionScaleKnown;scaling.F1s.acquisitionScaleKnown], ...
    [scaling.C1s.acquisitionScale;scaling.F1s.acquisitionScale], ...
    [scaling.C1s.acquisitionProvenance;scaling.F1s.acquisitionProvenance], ...
    'VariableNames', {'Region','SoftwareNormalization', ...
    'SoftwareNormalizationScale','AcquisitionScaleKnown', ...
    'AcquisitionScale','AcquisitionScaleProvenance'});
end

function out = ratioFields(FC)
out.F_over_C = FC;
out.F_atpct = FC/(1+FC)*100;
out.C_over_F = 1/FC;
out.CxF = sprintf("C%.3gF",1/FC);
end

function values = asStructArray(values)
if iscell(values), values = [values{:}]; end
end

function text = directionText(direction)
if direction < 0, text = "descending"; else, text = "ascending"; end
end

function printWarnings(region,warnings)
if isempty(warnings)
    fprintf("%s QC warnings: none\n",region);
else
    fprintf("%s QC warnings:\n",region);
    disp(warnings(:));
end
end
