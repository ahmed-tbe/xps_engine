function report = runSyntheticPipelineDemo
%RUNSYNTHETICPIPELINEDEMO Readable Phase 0G-3 end-to-end demonstration.
%
% Uses the same deterministic six-C1s/three-F1s synthetic case as the
% assertive test. It reports recovery details but does not replace tests.
% The true synthetic acquisition multipliers are supplied explicitly, so
% this also demonstrates the Phase 0G-4 scale-restoration path.

projectFolder = fileparts(mfilename("fullpath"));
cfg = jsondecode(fileread(fullfile(projectFolder, "config", ...
    "legacy_current_v1.json")));
peakShape = "gaussian";
cfg.preprocessing.background = "linear";

cSyntheticTruth = [ ...
    284.15 0.50 0.80; ... % sp2_C_C
    285.55 0.50 0.80; ... % C_CF_sp3
    287.40 0.50 0.80; ... % C_F
    289.30 0.50 0.80; ... % C_CF23_C_O
    291.40 0.50 0.80; ... % CF2
    293.50 0.50 0.80];   % CF3
fSyntheticTruth = [ ...
    684.70 0.60 0.80; ... % ionic/substrate-bound F
    686.70 0.60 0.80; ... % semi-covalent F-C
    688.20 0.60 0.80];   % covalent F-C
cAcquisitionScale = 2.0;
fAcquisitionScale = 13.0;
cEnergy = linspace(280, 297, 681).';
fEnergy = linspace(678, 693, 601).';
cRaw = cAcquisitionScale*syntheticGaussianSum(cEnergy, cSyntheticTruth);
fRaw = fAcquisitionScale*syntheticGaussianSum(fEnergy, fSyntheticTruth);

cFile = [tempname(tempdir) '.txt'];
fFile = [tempname(tempdir) '.txt'];
cleanupFiles = onCleanup(@() deleteIfPresent({cFile, fFile}));
writematrix([flipud(cEnergy) flipud(cRaw)], cFile, "Delimiter", "tab");
writematrix([flipud(fEnergy) flipud(fRaw)], fFile, "Delimiter", "tab");

% The actual current pipeline.
C = xps.readSpectrum(cFile);
F = xps.readSpectrum(fFile);
Cpre = xps.preprocessSpectrum(C, cfg.preprocessing);
Fpre = xps.preprocessSpectrum(F, cfg.preprocessing);
Cfit = xps.fitSpectrum(Cpre.energy, Cpre.y_fit, cfg.C1s, peakShape);
Ffit = xps.fitSpectrum(Fpre.energy, Fpre.y_fit, cfg.F1s, peakShape);
Ffit.peaks = xps.classifyF1sPeaks(Ffit.peaks, ...
    cfg.F1s.classification_boundaries_eV);
syntheticAcquisition.C1s = struct("known", true, ...
    "scale_factor", cAcquisitionScale, "provenance", "synthetic truth");
syntheticAcquisition.F1s = struct("known", true, ...
    "scale_factor", fAcquisitionScale, "provenance", "synthetic truth");
scaling = xps.buildQuantificationScaling(Cpre, Fpre, syntheticAcquisition);
comp = xps.calculateComposition(Cfit.peaks, Ffit.peaks, ...
    cfg.sensitivity_factors.C1s, cfg.sensitivity_factors.F1s, 0, scaling);

% Truth converted to each independently normalized fitting scale.
cExpectedAreas = cAcquisitionScale*cSyntheticTruth(:,2).'/Cpre.scale;
fExpectedAreas = fAcquisitionScale*fSyntheticTruth(:,2).'/Fpre.scale;
cRecoveredPhysicalAreas = [Cfit.peaks.area]*Cpre.scale/cAcquisitionScale;
fRecoveredPhysicalAreas = [Ffit.peaks.area]*Fpre.scale/fAcquisitionScale;
cAreaErrorPct = 100*relativeError([Cfit.peaks.area], cExpectedAreas);
fAreaErrorPct = 100*relativeError([Ffit.peaks.area], fExpectedAreas);

cTable = table(string({Cfit.peaks.id}).', cSyntheticTruth(:,1), ...
    [Cfit.peaks.center_eV].', ...
    abs([Cfit.peaks.center_eV].'-cSyntheticTruth(:,1)), ...
    cSyntheticTruth(:,3), [Cfit.peaks.FWHM_eV].', ...
    abs([Cfit.peaks.FWHM_eV].'-cSyntheticTruth(:,3)), ...
    cSyntheticTruth(:,2), cExpectedAreas.', [Cfit.peaks.area].', ...
    cRecoveredPhysicalAreas.', cAreaErrorPct.', ...
    'VariableNames', {'ID', 'SyntheticTruthCenter_eV', 'FitCenter_eV', ...
    'CenterError_eV', 'SyntheticTruthFWHM_eV', 'FitFWHM_eV', ...
    'FWHMError_eV', 'SyntheticTruthArea', 'ExpectedNormalizedFitArea', ...
    'RecoveredNormalizedFitArea', 'RecoveredPhysicalArea', ...
    'RelativeAreaError_pct'});

fTable = table(string({Ffit.peaks.id}).', fSyntheticTruth(:,1), ...
    [Ffit.peaks.center_eV].', ...
    abs([Ffit.peaks.center_eV].'-fSyntheticTruth(:,1)), ...
    fSyntheticTruth(:,3), [Ffit.peaks.FWHM_eV].', ...
    abs([Ffit.peaks.FWHM_eV].'-fSyntheticTruth(:,3)), ...
    fSyntheticTruth(:,2), fExpectedAreas.', [Ffit.peaks.area].', ...
    fRecoveredPhysicalAreas.', fAreaErrorPct.', ...
    string({Ffit.peaks.chemical_assignment}).', ...
    [Ffit.peaks.include_in_carbon_bound_F].', ...
    'VariableNames', {'ID', 'SyntheticTruthCenter_eV', 'FitCenter_eV', ...
    'CenterError_eV', 'SyntheticTruthFWHM_eV', 'FitFWHM_eV', ...
    'FWHMError_eV', 'SyntheticTruthArea', 'ExpectedNormalizedFitArea', ...
    'RecoveredNormalizedFitArea', 'RecoveredPhysicalArea', ...
    'RelativeAreaError_pct', ...
    'Classification', 'IncludedInCarbonBoundF'});

cAreas = cSyntheticTruth(:,2).';
truthWeightedFC = (cAreas(3)+2*cAreas(5)+3*cAreas(6))/sum(cAreas);
truthLegacyFC = ((sum(cAreas)-cAreas(1))/sum(cAreas))/3;
truthWeightedCxF = 1/truthWeightedFC;
truthLegacyCxF = 1/truthLegacyFC;
compositionTable = table( ...
    ["Weighted C1s F/C"; "Weighted CxF (C/F)"; ...
     "Legacy C1s F/C"; "Legacy CxF (C/F)"], ...
    [truthWeightedFC; truthWeightedCxF; truthLegacyFC; truthLegacyCxF], ...
    [comp.weighted.F_over_C; comp.weighted.C_over_F; ...
     comp.legacy.F_over_C; comp.legacy.C_over_F], ...
    100*[relativeError(comp.weighted.F_over_C, truthWeightedFC); ...
         relativeError(comp.weighted.C_over_F, truthWeightedCxF); ...
         relativeError(comp.legacy.F_over_C, truthLegacyFC); ...
         relativeError(comp.legacy.C_over_F, truthLegacyCxF)], ...
    'VariableNames', {'Metric', 'SyntheticTruthValue', ...
    'RetrievedValue', 'RelativeError_pct'});

fAreas = fSyntheticTruth(:,2).';
SC = cfg.sensitivity_factors.C1s;
SF = cfg.sensitivity_factors.F1s;
trueCarbonBoundFC = (sum(fAreas(2:3))/SF)/(sum(cAreas)/SC);
trueTotalFC = (sum(fAreas)/SF)/(sum(cAreas)/SC);
crossRegionTable = makeCrossRegionTable( ...
    ["Carbon-bound F/C";"Total-F F/C"], ...
    [trueCarbonBoundFC;trueTotalFC], ...
    [comp.carbonBound.F_over_C;comp.totalF.F_over_C]);

acceptance = struct( ...
    'centerTolerance_eV', 0.04, ...
    'fwhmTolerance_eV', 0.10, ...
    'areaTolerance_pct', 8, ...
    'minimumR2', 0.995, ...
    'maxC1sAreaError_pct', max(cAreaErrorPct), ...
    'maxF1sAreaError_pct', max(fAreaErrorPct), ...
    'C1sR2', Cfit.metrics.R2, ...
    'F1sR2', Ffit.metrics.R2);
acceptance.passesC1s = max(abs([Cfit.peaks.center_eV].'-cSyntheticTruth(:,1))) <= ...
    acceptance.centerTolerance_eV && ...
    max(abs([Cfit.peaks.FWHM_eV].'-cSyntheticTruth(:,3))) <= acceptance.fwhmTolerance_eV && ...
    acceptance.maxC1sAreaError_pct <= acceptance.areaTolerance_pct && ...
    acceptance.C1sR2 >= acceptance.minimumR2;
acceptance.passesF1s = max(abs([Ffit.peaks.center_eV].'-fSyntheticTruth(:,1))) <= ...
    acceptance.centerTolerance_eV && ...
    max(abs([Ffit.peaks.FWHM_eV].'-fSyntheticTruth(:,3))) <= acceptance.fwhmTolerance_eV && ...
    acceptance.maxF1sAreaError_pct <= acceptance.areaTolerance_pct && ...
    acceptance.F1sR2 >= acceptance.minimumR2;

fprintf("\n========================================================================\n");
fprintf("  PHASE 0G-3: SYNTHETIC FULL-PIPELINE DEMONSTRATION\n");
fprintf("========================================================================\n");
fprintf("Path: read -> preprocess -> fit -> F1s classification -> composition\n");
fprintf("All centers, widths, and areas below are artificial synthetic test values,\n");
fprintf("not Ruoff reference values or optimizer targets.\n");
fprintf("C/F acquisition multipliers: C1s=%.1f, F1s=%.1f\n", ...
    cAcquisitionScale, fAcquisitionScale);
fprintf("Preprocessing: max normalization; explicit background=%s\n", ...
    cfg.preprocessing.background);
fprintf("Recorded scales: C1s=%.6g, F1s=%.6g\n", Cpre.scale, Fpre.scale);
fprintf("C1s background: [%.6g, %.6g]; F1s: [%.6g, %.6g]\n\n", ...
    min(Cpre.background), max(Cpre.background), min(Fpre.background), max(Fpre.background));

fprintf("===== C1s component recovery =====\n");
disp(cTable);
fprintf("===== F1s component recovery and classification =====\n");
disp(fTable);
fprintf("===== C1s composition recovery =====\n");
disp(compositionTable);
fprintf("===== Scale-restored cross-region recovery (Phase 0G-4) =====\n");
disp(crossRegionTable);
fprintf("\n===== Acceptance summary =====\n");
fprintf("C1s: max area error=%.3f%%, R2=%.6f, pass=%d\n", ...
    acceptance.maxC1sAreaError_pct, acceptance.C1sR2, acceptance.passesC1s);
fprintf("F1s: max area error=%.3f%%, R2=%.6f, pass=%d\n", ...
    acceptance.maxF1sAreaError_pct, acceptance.F1sR2, acceptance.passesF1s);
fprintf("Linear is explicit because this deterministic signal has exactly zero\n");
fprintf("additive background; the AsLS-default failure remains a separate test.\n");

xps.plotFitComponents(Cpre, Cfit, "Synthetic C 1s - generic 0G pipeline");
xps.plotFitComponents(Fpre, Ffit, "Synthetic F 1s - generic 0G pipeline");

report = struct("Cfit", Cfit, "Ffit", Ffit, "composition", comp, ...
    "scaling", scaling, ...
    "C1sRecovery", cTable, "F1sRecovery", fTable, ...
    "compositionRecovery", compositionTable, ...
    "crossRegionRecovery", crossRegionTable, ...
    "cSyntheticTruth", cSyntheticTruth, ...
    "fSyntheticTruth", fSyntheticTruth, "acceptance", acceptance, ...
    "Cpre", Cpre, "Fpre", Fpre);
end

function T = makeCrossRegionTable(labels, trueFC, retrievedFC)
trueCx = 1./trueFC;
retrievedCx = 1./retrievedFC;
T = table(labels, trueFC, retrievedFC, ...
    100*relativeError(retrievedFC,trueFC), ...
    trueCx, retrievedCx, 100*relativeError(retrievedCx,trueCx), ...
    compose("C%.3gF",trueCx), compose("C%.3gF",retrievedCx), ...
    'VariableNames', {'Quantity','SyntheticTruth_F_over_C', ...
    'Retrieved_F_over_C','F_over_C_RelativeError_pct', ...
    'SyntheticTruth_C_over_F','Retrieved_C_over_F', ...
    'C_over_F_RelativeError_pct','SyntheticTruth_CxF','Retrieved_CxF'});
end

function y = syntheticGaussianSum(energy, truth)
y = zeros(size(energy));
for i = 1:size(truth,1)
    sigma = truth(i,3)/(2*sqrt(2*log(2)));
    y = y + truth(i,2)/(sigma*sqrt(2*pi)) .* ...
        exp(-0.5*((energy-truth(i,1))/sigma).^2);
end
end

function values = relativeError(actual, expected)
values = abs(actual-expected)./expected;
end

function deleteIfPresent(files)
for i = 1:numel(files)
    if isfile(files{i})
        delete(files{i});
    end
end
end
