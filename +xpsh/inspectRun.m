function status = inspectRun(plan,outputFolder,manifest,currentFingerprint)
%INSPECTRUN Read checkpoint status without creating or modifying files.

arguments
    plan (1,1) struct
    outputFolder (1,1) string
    manifest (1,1) struct
    currentFingerprint (1,1) string = ""
end
checkpointRoot=fullfile(outputFolder,"checkpoints");
n=numel(plan.cells);
completed=zeros(n,1); errors=zeros(n,1); cellCheckpoint=false(n,1);
for i=1:n
    cellDef=plan.cells(i);
    ids=xpsh.completedTrials(checkpointRoot,string(manifest.run_fingerprint), ...
        string(cellDef.cell_key));
    completed(i)=numel(ids);
    cellCheckpoint(i)=isfile(fullfile(checkpointRoot,cellDef.cell_key, ...
        "cell_complete.mat"));
    for id=ids.'
        value=load(fullfile(checkpointRoot,cellDef.cell_key, ...
            compose("trial_%04d.mat",id)),"payload");
        errors(i)=errors(i)+double(string(value.payload.status)=="error");
    end
end
inventory=xpsh.inventoryTable(plan);
cellStatus=table(inventory.FamilyID,inventory.FamilyName,inventory.CellKey, ...
    inventory.InitialTrials,completed,errors,cellCheckpoint, ...
    VariableNames=["FamilyID","FamilyName","CellKey","PlannedTrials", ...
    "CompletedTrials","ErrorTrials","CellCheckpointPresent"]);
complete=all(completed==inventory.InitialTrials) && all(cellCheckpoint);
if strlength(currentFingerprint)==0
    fingerprintMatch=missing;
else
    fingerprintMatch=string(manifest.run_fingerprint)==currentFingerprint;
end
status=struct("run_status",conditionalStatus(complete,sum(completed)), ...
    "output_folder",outputFolder,"run_mode",string(manifest.run_mode), ...
    "plan_version",string(manifest.plan_version), ...
    "plan_sha256",string(manifest.plan_sha256), ...
    "run_fingerprint",string(manifest.run_fingerprint), ...
    "fingerprint_matches_current_code_config",fingerprintMatch, ...
    "planned_cells",n,"completed_cells",nnz(cellCheckpoint), ...
    "planned_trials",sum(inventory.InitialTrials), ...
    "completed_trials",sum(completed),"error_trials",sum(errors), ...
    "remaining_trials",sum(inventory.InitialTrials)-sum(completed), ...
    "cell_status",cellStatus);
end

function value=conditionalStatus(complete,n)
if complete,value="complete";elseif n==0,value="initialized_no_trials";else,value="in_progress";end
end
