function manifest = createAmendmentManifest(plan,projectFolder,runMode)
%CREATEAMENDMENTMANIFEST Provenance for the isolated v1.0.1 execution subset.

arguments
    plan (1,1) struct
    projectFolder (1,1) string
    runMode (1,1) string {mustBeMember(runMode, ...
        ["amendment_dry_run","amendment","amendment_smoke"])}
end
baseMode="formal";
if runMode=="amendment_dry_run",baseMode="dry_run";end
if runMode=="amendment_smoke",baseMode="smoke";end
manifest=xpsh.createManifest(plan,projectFolder,baseMode);

formalFolder=fullfile(projectFolder,"results","phase0h_formal_v1_0_0");
original=jsondecode(fileread(fullfile(formalFolder,"manifest.json")));
approvedPlanHash="1f932b278de41dc14154191833f45b5fcf55f3b5a01edd7a661ddcbcf2f556bf";
approvedExecutionFingerprint= ...
    "93c6ad3a88ba0245be2043c06ca20c0adb62033989f051a6e71e340d31e292b4";
if string(original.plan_sha256)~=approvedPlanHash || ...
        string(original.code_config_fingerprint)~=approvedExecutionFingerprint
    error("xpsh:createAmendmentManifest:OriginalProvenanceMismatch", ...
        "The immutable v1.0.0 run does not have the approved provenance.");
end

rootSources=[ ...
    "PHASE_0H_EXECUTION_AMENDMENT_v1.0.1.md";
    "runPhase0HExecutionAmendment.m";
    "runPhase0HAmendmentDryRun.m";
    "runPhase0HAmendmentSmokeTest.m";
    "getPhase0HExecutionAmendmentStatus.m"];
records=manifest.files;
known=string({records.path}).';
for path=rootSources.'
    if ~isfile(fullfile(projectFolder,path)),continue;end
    if any(known==path),continue;end
    records(end+1,1)=struct("path",path, ...
        "sha256",xpsh.sha256File(fullfile(projectFolder,path))); %#ok<AGROW>
end
[~,order]=sort(string({records.path}));records=records(order);
lines=strings(numel(records),1);
for i=1:numel(records)
    lines(i)=string(records(i).path)+":"+string(records(i).sha256);
end
codeConfigFingerprint=xpsh.sha256Text(lines);
cellKeys=string({plan.cells.cell_key}).';
executionFingerprint=xpsh.sha256Text([ ...
    "amendment_version:1.0.1";
    "original_plan_sha256:"+approvedPlanHash;
    "original_execution_fingerprint:"+approvedExecutionFingerprint;
    "amended_code_config_fingerprint:"+codeConfigFingerprint;
    "cells:"+strjoin(cellKeys,",")]);

manifest.manifest_id="phase0h_execution_amendment_manifest";
manifest.manifest_version="1.0.1";
manifest.run_mode=runMode;
manifest.status=statusFor(runMode);
manifest.files=records;
manifest.code_config_fingerprint=codeConfigFingerprint;
manifest.amended_execution_fingerprint=executionFingerprint;
manifest.run_fingerprint=approvedPlanHash+":"+executionFingerprint;
manifest.original_frozen_plan=struct("plan_id",string(original.plan_id), ...
    "plan_version",string(original.plan_version), ...
    "plan_sha256",approvedPlanHash);
manifest.original_execution=struct( ...
    "code_config_fingerprint",approvedExecutionFingerprint, ...
    "run_fingerprint",string(original.run_fingerprint), ...
    "results_directory","results/phase0h_formal_v1_0_0", ...
    "immutable",true);
manifest.amendment=struct("amendment_id",plan.amendment_id, ...
    "version",plan.amendment_version,"affected_cells",cellKeys, ...
    "trial_count",plan.initial_trial_count, ...
    "expected_optimizer_invocations",plan.expected_optimizer_invocations, ...
    "original_seeds_reused",runMode~="amendment_smoke", ...
    "seed_policy",plan.seed_policy, ...
    "rationale", ...
    "Correct generated-truth label-to-assignment schema adaptation for " + ...
    "Family 12 and legal deterministic initialization for disjoint " + ...
    "charging-shift intervals in F10_G2.", ...
    "exact_code_changes",codeChanges(), ...
    "unchanged_scientific_definitions",[ ...
    "acceptance thresholds";"composition models and equations"; ...
    "sensitivity factors";"fit bounds";"frozen cell definitions"]);
end

function changes=codeChanges
changes(1)=struct("change_id","truth_schema_adapter", ...
    "files",["+xpsh/executeTrial.m";"+xpsh/truthAsFittedPeaks.m"], ...
    "description","Map generated truth.label to fitted-like assignment.");
changes(2)=struct("change_id","disjoint_initial_center_rule", ...
    "files",["+xpsh/generateFixture.m";"+xpsh/selectInitialCenter.m"], ...
    "description", ...
    "Retain intersection sampling; use configured nominal center when " + ...
    "the truth-centered interval and legal bounds are disjoint.");
end

function status=statusFor(mode)
if mode=="amendment"
    status="approved_amendment_execution";
elseif mode=="amendment_smoke"
    status="smoke_only_excluded_from_amendment_statistics";
else
    status="dry_run_only_no_amendment_trials";
end
end
