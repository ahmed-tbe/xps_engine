function T = inventoryTable(plan)
%INVENTORYTABLE Convert executable plan cells to a stable report table.

cells = plan.cells;
T = table([cells.family_id].',string({cells.family_name}).', ...
    [cells.cell_index].',string({cells.cell_id}).', ...
    string({cells.cell_key}).',string({cells.gate}).', ...
    [cells.trials].',[cells.starts].',[cells.pipelines_per_trial].', ...
    [cells.fit_required].',[cells.optimizer_invocations_per_trial].', ...
    [cells.trials].'.*[cells.optimizer_invocations_per_trial].', ...
    string({cells.description}).',VariableNames=["FamilyID","FamilyName", ...
    "CellIndex","CellID","CellKey","Gate","InitialTrials","Starts", ...
    "PipelinesPerTrial","FitRequired","OptimizerInvocationsPerTrial", ...
    "InitialOptimizerInvocations","Description"]);
end
