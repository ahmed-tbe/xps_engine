function summary = generateFinalPhase0HSummary(extensionFolder,options)
%GENERATEFINALPHASE0HSUMMARY Combine accepted N=100 data with extensions.
%
% Uses N=400 for exactly the 42 predeclared cells and N=100 for the other
% 50 cells. Source executions are read-only and every trial retains its
% source run/fingerprint. Frozen gates and thresholds are reused unchanged.

arguments
    extensionFolder (1,1) string = ""
    options.OutputFolder (1,1) string = ""
end
projectFolder=string(fileparts(mfilename("fullpath")));
if strlength(extensionFolder)==0
    extensionFolder=fullfile(projectFolder,"results", ...
        "phase0h_borderline_extension_v1_0_0");
end
acceptedFolder=fullfile(projectFolder,"results","phase0h_unified_v1_0_1");
outputFolder=options.OutputFolder;
if strlength(outputFolder)==0
    outputFolder=fullfile(projectFolder,"results","phase0h_final_v1_0_0");
end
assertSeparateOutput(outputFolder,[acceptedFolder;extensionFolder]);
if isfolder(outputFolder) && ~isempty(dir(fullfile(outputFolder,"*")))
    error("generateFinalPhase0HSummary:OutputExists", ...
        "Final summary folder must be new or empty: %s",outputFolder);
end

extensionPlan=buildPhase0HExtensionPlan(projectFolder);
storedManifest=readManifest(extensionFolder);
currentManifest=createPhase0HExtensionManifest(extensionPlan,projectFolder,"extension");
status=inspectPhase0HExtensionRun(extensionPlan,extensionFolder,storedManifest, ...
    string(currentManifest.run_fingerprint));
if status.run_status~="complete" || ...
        ~logical(status.fingerprint_matches_current_extension) || ...
        status.completed_new_trials~=12600
    error("generateFinalPhase0HSummary:ExtensionIncomplete", ...
        "The approved extension must be complete and fingerprint-valid.");
end
if string(storedManifest.plan_sha256)~=string(currentManifest.plan_sha256) || ...
        string(storedManifest.extension_execution_fingerprint)~= ...
            string(currentManifest.extension_execution_fingerprint)
    error("generateFinalPhase0HSummary:ExtensionProvenance", ...
        "Stored extension provenance does not match approved execution code.");
end

acceptedFile=fullfile(acceptedFolder,"phase0h_unified_summary.mat");
acceptedValue=load(acceptedFile,"summary"); accepted=acceptedValue.summary;
if ~logical(accepted.provenance_validation_passed) || ...
        accepted.cell_count~=92 || accepted.trial_count~=9200 || ...
        accepted.execution_errors~=0 || ...
        xpsh.sha256File(acceptedFile)~= ...
            string(storedManifest.parent_results.accepted_unified_summary_sha256)
    error("generateFinalPhase0HSummary:AcceptedParentInvalid", ...
        "Accepted initial unified summary does not match extension provenance.");
end

sourceFolders=[fullfile(projectFolder,"results","phase0h_formal_v1_0_0"); ...
    fullfile(projectFolder,"results","phase0h_execution_amendment_v1_0_1"); ...
    acceptedFolder;extensionFolder];
before=snapshots(sourceFolders);
trialCells=cell(extensionPlan.new_trial_count,1); indexCells=cell(extensionPlan.new_trial_count,1);
peakCells={}; compositionCells={}; pairCells={}; contributionCells=cell(42,1);
cursor=0; peakCursor=0; compositionCursor=0; pairCursor=0;
fprintf("Indexing completed Phase 0H borderline extensions read-only...\n");
for i=1:numel(extensionPlan.cells)
    c=extensionPlan.cells(i); key=string(c.cell_key);
    validateCellCheckpoint(extensionFolder,key,c,string(storedManifest.run_fingerprint));
    contributionCells{i}=struct("FamilyID",c.family_id, ...
        "FamilyName",string(c.family_name),"CellKey",key, ...
        "SourceRunID","phase0h_borderline_extension_v1_0_0", ...
        "SourceExecutionFingerprint", ...
            string(storedManifest.extension_execution_fingerprint), ...
        "SourceRunFingerprint",string(storedManifest.run_fingerprint), ...
        "FirstTrialID",101,"LastTrialID",400,"Trials",300, ...
        "SeedNamespace",string(storedManifest.seed_namespace), ...
        "SeedScheduleVerified",true);
    for trialID=101:400
        file=fullfile(extensionFolder,"checkpoints",key, ...
            compose("trial_%04d.mat",trialID));
        value=load(file,"payload","runFingerprint","cellKey","trialID");
        validateTrial(value,key,trialID,c,string(storedManifest.run_fingerprint),file);
        [trial,peaks,compositions,pair]=analyzePhase0HUnifiedTrial( ...
            value.payload,c,"phase0h_borderline_extension_v1_0_0", ...
            string(storedManifest.extension_execution_fingerprint));
        cursor=cursor+1; trialCells{cursor}=trial;
        indexCells{cursor}=struct("FamilyID",c.family_id, ...
            "FamilyName",string(c.family_name),"CellKey",key, ...
            "TrialID",trialID,"SourceRunID", ...
            "phase0h_borderline_extension_v1_0_0", ...
            "SourceExecutionFingerprint", ...
                string(storedManifest.extension_execution_fingerprint), ...
            "SeedScheduleVerified",true,"CheckpointPath",string(file));
        for j=1:numel(peaks),peakCursor=peakCursor+1;peakCells{peakCursor,1}=peaks(j);end %#ok<AGROW>
        for j=1:numel(compositions)
            compositionCursor=compositionCursor+1;compositionCells{compositionCursor,1}=compositions(j); %#ok<AGROW>
        end
        if pair.Applicable,pairCursor=pairCursor+1;pairCells{pairCursor,1}=pair;end %#ok<AGROW>
    end
    if mod(i,5)==0 || i==numel(extensionPlan.cells)
        fprintf("  indexed %d/%d extension cells (%d/%d new trials)\n", ...
            i,numel(extensionPlan.cells),cursor,extensionPlan.new_trial_count);
    end
end
if cursor~=12600,error("generateFinalPhase0HSummary:TrialCount","Expected 12,600 extension records.");end

extensionTrials=struct2table(vertcat(trialCells{:}));
extensionIndex=struct2table(vertcat(indexCells{:}));
extensionPeaks=struct2table(vertcat(peakCells{:}));
extensionCompositions=struct2table(vertcat(compositionCells{:}));
if isempty(pairCells),extensionPairs=accepted.pairMetrics([],:);
else,extensionPairs=struct2table(vertcat(pairCells{:}));end
trialTable=[accepted.trialMetrics;extensionTrials];
trialIndex=[accepted.trialIndex;extensionIndex];
peakTable=[accepted.peakMetrics;extensionPeaks];
compositionTable=[accepted.compositionMetrics;extensionCompositions];
pairTable=[accepted.pairMetrics;extensionPairs];

fullPlan=xpsh.buildPlan(projectFolder); selected=string({extensionPlan.cells.cell_key});
for i=1:numel(fullPlan.cells)
    if ismember(string(fullPlan.cells(i).cell_key),selected)
        fullPlan.cells(i).trials=400;
    end
end
gate=summarizePhase0HUnifiedResults(fullPlan,trialTable,peakTable, ...
    compositionTable,pairTable);
breakdown=buildPhase0HFailureBreakdown(gate.cellSummary, ...
    gate.peakMetricSummary,gate.compositionMetricSummary, ...
    gate.rateSummary,trialTable);

[counts,keys]=groupcounts(string(trialTable.CellKey));
expected=100*ones(numel(keys),1); expected(ismember(keys,selected))=400;
countsValid=numel(keys)==92 && all(counts==expected) && ...
    nnz(counts==400)==42 && nnz(counts==100)==50;
provenanceValid=countsValid && all(trialIndex.SeedScheduleVerified) && ...
    height(unique(trialIndex(:,["CellKey","TrialID"]),"rows"))==height(trialIndex) && ...
    status.fingerprint_matches_current_extension;
after=snapshots(sourceFolders);
if ~isequaln(before,after)
    error("generateFinalPhase0HSummary:SourceMutation", ...
        "A source result directory changed during read-only reporting.");
end

initialContributions=accepted.cellProvenance;
initialContributions.FirstTrialID=ones(height(initialContributions),1);
initialContributions.LastTrialID=100*ones(height(initialContributions),1);
initialContributions.SeedNamespace=repmat("phase0h_initial_trials_1_100", ...
    height(initialContributions),1);
initialContributions.SeedScheduleVerified=true(height(initialContributions),1);
if ismember("OriginalSeedsReused",string(initialContributions.Properties.VariableNames))
    initialContributions=removevars(initialContributions,"OriginalSeedsReused");
end
extensionContributions=struct2table(vertcat(contributionCells{:}));
extensionContributions=extensionContributions(:, ...
    initialContributions.Properties.VariableNames);
cellExecutionProvenance=[initialContributions;extensionContributions];
post=postprocessingProvenance(projectFolder);
summary=struct("summary_id","phase0h_final_mixed_N_read_only_summary", ...
    "summary_version","1.0.0","generated_at",string(datetime("now", ...
    "TimeZone","America/Chicago","Format","yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    "plan_sha256",string(storedManifest.plan_sha256), ...
    "extension_execution_fingerprint", ...
        string(storedManifest.extension_execution_fingerprint), ...
    "source_runs_immutable",true,"plotting_performed",false, ...
    "cell_count",92,"trial_count",height(trialTable), ...
    "extended_cell_count",42,"extended_cell_N",400, ...
    "unextended_cell_count",50,"unextended_cell_N",100, ...
    "execution_errors",nnz(trialTable.ExecutionError), ...
    "nonconverged_trials",nnz(~trialTable.TrialConverged), ...
    "provenance_validation_passed",provenanceValid, ...
    "observed_rates_are_primary_gates",true, ...
    "wilson_intervals_are_uncertainty_only",true, ...
    "thresholds_unchanged",true,"trialIndex",trialIndex, ...
    "trialMetrics",trialTable,"peakMetrics",peakTable, ...
    "compositionMetrics",compositionTable,"pairMetrics",pairTable, ...
    "cellExecutionProvenance",cellExecutionProvenance, ...
    "cellSummary",gate.cellSummary,"rateSummary",gate.rateSummary, ...
    "peakMetricSummary",gate.peakMetricSummary, ...
    "compositionMetricSummary",gate.compositionMetricSummary, ...
    "failureBreakdown",breakdown,"postprocessing",post, ...
    "output_folder",outputFolder);

if ~isfolder(outputFolder),mkdir(outputFolder);end
writetable(cellExecutionProvenance,fullfile(outputFolder,"cell_execution_provenance.csv"));
writetable(trialIndex,fullfile(outputFolder,"final_trial_index.csv"));
writetable(gate.cellSummary,fullfile(outputFolder,"gate_summary_by_cell.csv"));
writetable(gate.rateSummary,fullfile(outputFolder,"qc_rate_summary.csv"));
writetable(gate.peakMetricSummary,fullfile(outputFolder,"peak_distribution_summary.csv"));
writetable(gate.compositionMetricSummary,fullfile(outputFolder,"composition_distribution_summary.csv"));
writetable(breakdown,fullfile(outputFolder,"failure_breakdown_by_cell.csv"));
save(fullfile(outputFolder,"phase0h_final_summary.mat"),"summary","-v7.3");
xpsh.writeJsonAtomic(fullfile(outputFolder,"final_provenance.json"),struct( ...
    "summary_id",summary.summary_id,"summary_version",summary.summary_version, ...
    "plan_sha256",summary.plan_sha256, ...
    "extension_execution_fingerprint",summary.extension_execution_fingerprint, ...
    "initial_unified_summary_sha256",xpsh.sha256File(acceptedFile), ...
    "extended_cells_N",400,"extended_cell_count",42, ...
    "unextended_cells_N",100,"unextended_cell_count",50, ...
    "trial_count",height(trialTable),"execution_errors",summary.execution_errors, ...
    "provenance_validation_passed",provenanceValid, ...
    "observed_rates_are_primary_gates",true, ...
    "wilson_intervals_are_uncertainty_only",true, ...
    "postprocessing",post));
fprintf(["Final Phase 0H summary written to %s\nCells=92; trials=%d; " + ...
    "N=400 cells=42; N=100 cells=50; errors=%d; nonconverged=%d; provenance=%s.\n"], ...
    outputFolder,height(trialTable),summary.execution_errors, ...
    summary.nonconverged_trials,string(provenanceValid));
end

function manifest=readManifest(folder)
file=fullfile(folder,"manifest.json");
if ~isfile(file),error("generateFinalPhase0HSummary:MissingManifest","Missing %s.",file);end
manifest=jsondecode(fileread(file));
end

function validateCellCheckpoint(folder,key,c,runFingerprint)
file=fullfile(folder,"checkpoints",key,"cell_complete.mat");
if ~isfile(file),error("generateFinalPhase0HSummary:MissingCell","Missing %s.",file);end
v=load(file,"runFingerprint","cellKey","completedTrialIDs");
if string(v.runFingerprint)~=runFingerprint || string(v.cellKey)~=key || ...
        ~isequal(v.completedTrialIDs,(c.extension_first_trial:c.extension_last_trial).')
    error("generateFinalPhase0HSummary:CellIdentity","Cell checkpoint mismatch: %s.",file);
end
end

function validateTrial(v,key,id,c,runFingerprint,file)
if string(v.runFingerprint)~=runFingerprint || string(v.cellKey)~=key || ...
        v.trialID~=id || string(v.payload.cell_key)~=key || v.payload.trial_id~=id || ...
        ~isequaln(v.payload.seeds,xpsh.trialSeeds(c,id)) || ...
        string(v.payload.seed_namespace)~= ...
            "phase0h_borderline_extension_v1_0_0/trials_101_400"
    error("generateFinalPhase0HSummary:TrialIdentity", ...
        "Trial identity/seed/namespace mismatch: %s.",file);
end
end

function value=snapshots(folders)
value=cell(numel(folders),1);
for i=1:numel(folders),value{i}=phase0HResultIntegritySnapshot(folders(i));end
end

function p=postprocessingProvenance(projectFolder)
files=["generateFinalPhase0HSummary.m";"buildPhase0HFailureBreakdown.m"; ...
    "analyzePhase0HUnifiedTrial.m";"summarizePhase0HUnifiedResults.m"];
hashes=strings(numel(files),1);
for i=1:numel(files),hashes(i)=xpsh.sha256File(fullfile(projectFolder,files(i)));end
p=struct("version","1.0.0","files",files,"file_sha256",hashes, ...
    "combined_sha256",xpsh.sha256Text(strjoin(files+":"+hashes,newline)));
end

function assertSeparateOutput(outputFolder,sources)
output=canonical(outputFolder);
for source=sources.'
    one=canonical(source);
    if output==one || startsWith(output,one+string(filesep))
        error("generateFinalPhase0HSummary:ImmutableSource", ...
            "Final output must be outside immutable source folder %s.",source);
    end
end
end

function value=canonical(path)
value=lower(string(char(java.io.File(path).getCanonicalPath())));
end
