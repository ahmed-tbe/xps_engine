function status = getPhase0HExtensionStatus(outputFolder)
%GETPHASE0HEXTENSIONSTATUS Inspect extension progress without writes.

arguments
    outputFolder (1,1) string = ""
end
projectFolder=string(fileparts(mfilename("fullpath")));
if strlength(outputFolder)==0
    outputFolder=fullfile(projectFolder,"results", ...
        "phase0h_borderline_extension_v1_0_0");
end
plan=buildPhase0HExtensionPlan(projectFolder);
manifestFile=fullfile(outputFolder,"manifest.json");
if ~isfile(manifestFile)
    status=struct("run_status","not_started","output_folder",outputFolder, ...
        "planned_cells",plan.cell_count,"completed_cells",0, ...
        "planned_new_trials",plan.new_trial_count,"completed_new_trials",0, ...
        "execution_error_trials",0,"nonconverged_trials",0, ...
        "remaining_new_trials",plan.new_trial_count, ...
        "expected_optimizer_invocations",plan.expected_optimizer_invocations, ...
        "fingerprint_matches_current_extension",missing);
    fprintf("Phase 0H extension has not started: %s\n",outputFolder);
    return
end
manifest=jsondecode(fileread(manifestFile));
current=createPhase0HExtensionManifest(plan,projectFolder,"extension");
status=inspectPhase0HExtensionRun(plan,outputFolder,manifest, ...
    string(current.run_fingerprint));
fprintf(["Phase 0H extension status: %s; %d/%d new trials; %d/%d cells; " + ...
    "errors=%d; nonconverged=%d; fingerprint-match=%s.\n"], ...
    status.run_status,status.completed_new_trials,status.planned_new_trials, ...
    status.completed_cells,status.planned_cells,status.execution_error_trials, ...
    status.nonconverged_trials, ...
    string(status.fingerprint_matches_current_extension));
end
