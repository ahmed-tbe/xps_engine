function status = inspectPhase0HExtensionRun(plan,outputFolder,manifest,currentFingerprint)
%INSPECTPHASE0HEXTENSIONRUN Read extension status without modifying results.

arguments
    plan (1,1) struct
    outputFolder (1,1) string
    manifest (1,1) struct
    currentFingerprint (1,1) string = ""
end

root=fullfile(outputFolder,"checkpoints");
n=numel(plan.cells);
completed=zeros(n,1); errors=zeros(n,1); nonconverged=zeros(n,1);
cellCheckpoint=false(n,1); firstID=zeros(n,1); lastID=zeros(n,1);
for i=1:n
    c=plan.cells(i); firstID(i)=c.extension_first_trial;
    lastID(i)=c.extension_last_trial;
    ids=xpsh.completedTrials(root,string(manifest.run_fingerprint),string(c.cell_key));
    if any(ids<firstID(i)|ids>lastID(i))
        error("inspectPhase0HExtensionRun:UnexpectedTrialID", ...
            "Cell %s contains a trial outside 101:400.",c.cell_key);
    end
    completed(i)=numel(ids);
    cellCheckpoint(i)=isfile(fullfile(root,c.cell_key,"cell_complete.mat"));
    for id=ids.'
        value=load(fullfile(root,c.cell_key,compose("trial_%04d.mat",id)),"payload");
        payload=value.payload;
        errors(i)=errors(i)+double(string(payload.status)=="error");
        nonconverged(i)=nonconverged(i)+double(~isfield(payload,"trial_converged") || ...
            ~logical(payload.trial_converged));
    end
end

FamilyID=[plan.cells.family_id].';
FamilyName=string({plan.cells.family_name}).';
CellKey=string({plan.cells.cell_key}).';
PlannedNewTrials=[plan.cells.extension_trials].';
cellStatus=table(FamilyID,FamilyName,CellKey,firstID,lastID, ...
    PlannedNewTrials,completed,errors,nonconverged,cellCheckpoint, ...
    VariableNames=["FamilyID","FamilyName","CellKey","FirstTrialID", ...
    "LastTrialID","PlannedNewTrials","CompletedNewTrials", ...
    "ExecutionErrorTrials","NonconvergedTrials","CellCheckpointPresent"]);
complete=all(completed==PlannedNewTrials) && all(cellCheckpoint);
if strlength(currentFingerprint)==0
    fingerprintMatch=missing;
else
    fingerprintMatch=string(manifest.run_fingerprint)==currentFingerprint;
end
status=struct("run_status",statusText(complete,sum(completed)), ...
    "output_folder",outputFolder,"run_mode",string(manifest.run_mode), ...
    "plan_version",string(manifest.plan_version), ...
    "plan_sha256",string(manifest.plan_sha256), ...
    "extension_version",string(manifest.extension_version), ...
    "extension_execution_fingerprint", ...
        string(manifest.extension_execution_fingerprint), ...
    "run_fingerprint",string(manifest.run_fingerprint), ...
    "fingerprint_matches_current_extension",fingerprintMatch, ...
    "planned_cells",n,"completed_cells",nnz(cellCheckpoint), ...
    "planned_new_trials",sum(PlannedNewTrials), ...
    "completed_new_trials",sum(completed), ...
    "execution_error_trials",sum(errors), ...
    "nonconverged_trials",sum(nonconverged), ...
    "remaining_new_trials",sum(PlannedNewTrials)-sum(completed), ...
    "expected_optimizer_invocations",plan.expected_optimizer_invocations, ...
    "cell_status",cellStatus);
end

function value=statusText(complete,n)
if complete,value="complete";elseif n==0,value="initialized_no_trials";else,value="in_progress";end
end
