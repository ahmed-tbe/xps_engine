function report = runRuoffLikeSyntheticPipelineDemo(showPlots, verbose)
%RUNRUOFFLIKESYNTHETICPIPELINEDEMO Exact reference-derived synthetic case.
%
% C1s centers and fractions are used only to generate a noise-free
% synthetic spectrum. The fitter receives the generated spectrum and a
% separately labeled test configuration; it never receives the true areas.
% This is not a fit of real Sample A and is not a production model choice.

arguments
    showPlots (1,1) logical = true
    verbose (1,1) logical = true
end

projectFolder = fileparts(mfilename("fullpath"));
configFile = fullfile(projectFolder, "config", "test", ...
    "ruoff_like_sample_A_synthetic_v1.json");
cfg = jsondecode(fileread(configFile));
referenceFile = fullfile(projectFolder, string(cfg.reference_data_file));
reference = xps.loadReference(referenceFile);

configuredC = cfg.C1s.peaks;
referenceC = asStructArray( ...
    reference.direct_references.C1s_normal_emission.peaks);
nC = numel(configuredC);
cSyntheticTruth = zeros(nC,3); % center, physical area, FWHM
cIDs = strings(nC,1);
for i = 1:nC
    configuredPeak = indexedPeak(configuredC,i);
    cIDs(i) = string(configuredPeak.id);
    refIndex = find(string({referenceC.id}) == cIDs(i),1);
    if isempty(refIndex)
        error("runRuoffLikeSyntheticPipelineDemo:MissingReferencePeak", ...
            "No Ruoff reference entry exists for '%s'.",cIDs(i));
    end
    cSyntheticTruth(i,:) = [referenceC(refIndex).center_eV, ...
        cfg.synthetic_generation.C1s_total_physical_area* ...
        referenceC(refIndex).fraction_percent/100, ...
        cfg.synthetic_generation.C1s_FWHM_eV];
end

fCenters = cfg.synthetic_generation.F1s_centers_eV(:);
fAreas = cfg.synthetic_generation.F1s_physical_areas(:);
fSyntheticTruth = [fCenters, fAreas, ...
    repmat(cfg.synthetic_generation.F1s_FWHM_eV,numel(fCenters),1)];

cAcquisitionScale = ...
    cfg.synthetic_generation.C1s_acquisition_scale_factor;
fAcquisitionScale = ...
    cfg.synthetic_generation.F1s_acquisition_scale_factor;
cEnergy = linspace(280,297,681).';
fEnergy = linspace(682,691,451).';
cRaw = cAcquisitionScale*syntheticGaussianSum(cEnergy,cSyntheticTruth);
fRaw = fAcquisitionScale*syntheticGaussianSum(fEnergy,fSyntheticTruth);

cFile = [tempname(tempdir) '.txt'];
fFile = [tempname(tempdir) '.txt'];
cleanupFiles = onCleanup(@() deleteIfPresent({cFile,fFile}));
writematrix([flipud(cEnergy),flipud(cRaw)],cFile,"Delimiter","tab");
writematrix([flipud(fEnergy),flipud(fRaw)],fFile,"Delimiter","tab");

% Complete production chain with the isolated test configuration.
C = xps.readSpectrum(cFile);
F = xps.readSpectrum(fFile);
Cpre = xps.preprocessSpectrum(C,cfg.preprocessing);
Fpre = xps.preprocessSpectrum(F,cfg.preprocessing);
Cfit = xps.fitSpectrum(Cpre.energy,Cpre.y_fit,cfg.C1s, ...
    string(cfg.peak_shape));
Ffit = xps.fitSpectrum(Fpre.energy,Fpre.y_fit,cfg.F1s, ...
    string(cfg.peak_shape));
Ffit.peaks = xps.classifyF1sPeaks(Ffit.peaks, ...
    cfg.F1s.classification_boundaries_eV);

acquisition.C1s = struct("known",true, ...
    "scale_factor",cAcquisitionScale, ...
    "provenance","Ruoff-like deterministic synthetic fixture");
acquisition.F1s = struct("known",true, ...
    "scale_factor",fAcquisitionScale, ...
    "provenance","Ruoff-like deterministic synthetic fixture");
scaling = xps.buildQuantificationScaling(Cpre,Fpre,acquisition);
comp = xps.calculateComposition(Cfit.peaks,Ffit.peaks, ...
    cfg.sensitivity_factors.C1s,cfg.sensitivity_factors.F1s, ...
    cfg.composition.alpha_ambiguous,scaling);

cExpectedFitAreas = cAcquisitionScale*cSyntheticTruth(:,2).' / ...
    Cpre.softwareNormalizationScale;
fExpectedFitAreas = fAcquisitionScale*fSyntheticTruth(:,2).' / ...
    Fpre.softwareNormalizationScale;
cRecoveredPhysical = [Cfit.peaks.area].'* ...
    Cpre.softwareNormalizationScale/cAcquisitionScale;
fRecoveredPhysical = [Ffit.peaks.area].'* ...
    Fpre.softwareNormalizationScale/fAcquisitionScale;
cRecoveredFractions = 100*cRecoveredPhysical/sum(cRecoveredPhysical);
cReferenceFractions = 100*cSyntheticTruth(:,2)/sum(cSyntheticTruth(:,2));

% Apply the established C1s formulas to the exact published fractions,
% independently of the small numerical errors in the fitted areas. These
% are derived model values, not directly published Ruoff quantities.
referenceFractionPeaks = Cfit.peaks;
for i = 1:nC
    referenceFractionPeaks(i).area = cReferenceFractions(i)/100;
end
referenceFormulaComposition = xps.calculateComposition( ...
    referenceFractionPeaks,Ffit.peaks, ...
    cfg.sensitivity_factors.C1s,cfg.sensitivity_factors.F1s, ...
    cfg.composition.alpha_ambiguous,struct());
c1sFormulaConsistencyTable = makeC1sFormulaConsistencyTable( ...
    referenceFormulaComposition,reference);

cTable = table(cIDs,cSyntheticTruth(:,1),[Cfit.peaks.center_eV].', ...
    [Cfit.peaks.center_eV].'-cSyntheticTruth(:,1), ...
    cReferenceFractions,cRecoveredFractions, ...
    cRecoveredFractions-cReferenceFractions, ...
    100*(cRecoveredFractions-cReferenceFractions)./cReferenceFractions, ...
    cSyntheticTruth(:,3),[Cfit.peaks.FWHM_eV].', ...
    cSyntheticTruth(:,2),cExpectedFitAreas.',[Cfit.peaks.area].', ...
    cRecoveredPhysical, ...
    100*relativeError(cRecoveredPhysical,cSyntheticTruth(:,2)), ...
    'VariableNames', {'ID','RuoffDerivedSyntheticTruthCenter_eV', ...
    'FitCenter_eV','CenterError_eV', ...
    'RuoffDerivedSyntheticTruthFraction_pct','RecoveredFraction_pct', ...
    'FractionError_pp','RelativeFractionError_pct', ...
    'SyntheticTruthFWHM_eV','FitFWHM_eV','SyntheticTruthArea', ...
    'ExpectedNormalizedFitArea','RecoveredNormalizedFitArea', ...
    'RecoveredPhysicalArea','RelativeAreaError_pct'});

fTable = table(string({Ffit.peaks.id}).',fSyntheticTruth(:,1), ...
    [Ffit.peaks.center_eV].', ...
    [Ffit.peaks.center_eV].'-fSyntheticTruth(:,1), ...
    fSyntheticTruth(:,3),[Ffit.peaks.FWHM_eV].', ...
    fSyntheticTruth(:,2),fExpectedFitAreas.',[Ffit.peaks.area].', ...
    fRecoveredPhysical, ...
    100*relativeError(fRecoveredPhysical,fSyntheticTruth(:,2)), ...
    string({Ffit.peaks.chemical_assignment}).', ...
    [Ffit.peaks.include_in_carbon_bound_F].', ...
    'VariableNames', {'ID','SyntheticTruthCenter_eV','FitCenter_eV', ...
    'CenterError_eV','SyntheticTruthFWHM_eV','FitFWHM_eV', ...
    'SyntheticTruthArea','ExpectedNormalizedFitArea', ...
    'RecoveredNormalizedFitArea','RecoveredPhysicalArea', ...
    'RelativeAreaError_pct','Classification','IncludedInCarbonBoundF'});

SC = cfg.sensitivity_factors.C1s;
SF = cfg.sensitivity_factors.F1s;
trueCarbonBoundFC = (sum(fSyntheticTruth(2:3,2))/SF) / ...
    (sum(cSyntheticTruth(:,2))/SC);
trueTotalFC = (sum(fSyntheticTruth(:,2))/SF) / ...
    (sum(cSyntheticTruth(:,2))/SC);
crossRegionTable = makeCrossRegionTable( ...
    ["Carbon-bound F/C";"Total-F F/C"], ...
    [trueCarbonBoundFC;trueTotalFC], ...
    [comp.carbonBound.F_over_C;comp.totalF.F_over_C]);

acceptance = struct( ...
    "centerTolerance_eV",0.02, ...
    "FWHMTolerance_eV",0.05, ...
    "relativeAreaTolerance",0.02, ...
    "minimumR2",0.999);
acceptance.maxC1sCenterError_eV = max(abs( ...
    [Cfit.peaks.center_eV].'-cSyntheticTruth(:,1)));
acceptance.maxF1sCenterError_eV = max(abs( ...
    [Ffit.peaks.center_eV].'-fSyntheticTruth(:,1)));
acceptance.maxC1sFWHMError_eV = max(abs( ...
    [Cfit.peaks.FWHM_eV].'-cSyntheticTruth(:,3)));
acceptance.maxF1sFWHMError_eV = max(abs( ...
    [Ffit.peaks.FWHM_eV].'-fSyntheticTruth(:,3)));
acceptance.maxC1sAreaError = max(relativeError( ...
    cRecoveredPhysical,cSyntheticTruth(:,2)));
acceptance.maxF1sAreaError = max(relativeError( ...
    fRecoveredPhysical,fSyntheticTruth(:,2)));
acceptance.passes = ...
    acceptance.maxC1sCenterError_eV <= acceptance.centerTolerance_eV && ...
    acceptance.maxF1sCenterError_eV <= acceptance.centerTolerance_eV && ...
    acceptance.maxC1sFWHMError_eV <= acceptance.FWHMTolerance_eV && ...
    acceptance.maxF1sFWHMError_eV <= acceptance.FWHMTolerance_eV && ...
    acceptance.maxC1sAreaError <= acceptance.relativeAreaTolerance && ...
    acceptance.maxF1sAreaError <= acceptance.relativeAreaTolerance && ...
    Cfit.metrics.R2 >= acceptance.minimumR2 && ...
    Ffit.metrics.R2 >= acceptance.minimumR2;

if verbose
    fprintf("\n========================================================================\n");
    fprintf("  RUOFF-LIKE REFERENCE-DERIVED SYNTHETIC PIPELINE DEMONSTRATION\n");
    fprintf("========================================================================\n");
    fprintf("This is noise-free generated data, not real Sample A. Reference values\n");
    fprintf("generate the C1s signal and are not supplied as fitted areas.\n");
    fprintf("Configuration: %s (test-only)\n",cfg.profile_name);
    fprintf("Background: %s; peak shape: %s\n", ...
        cfg.preprocessing.background,cfg.peak_shape);
    fprintf("Legacy conflict preserved: %s\n\n",cfg.legacy_conflict_note);
    fprintf("===== Reference-derived C1s synthetic recovery =====\n");
    disp(cTable);
    fprintf("===== Locked three-peak F1s synthetic recovery =====\n");
    disp(fTable);
    fprintf("===== C1s formula consistency against Ruoff validation reference =====\n");
    fprintf("DirectRuoffReference values are directly recorded project references.\n");
    fprintf("ModelAppliedToRuoffPublishedFractions values are derived by our\n");
    fprintf("candidate formulas and are not directly published Ruoff values.\n");
    disp(c1sFormulaConsistencyTable);
    fprintf("===== Scale-restored cross-region recovery (Phase 0G-4) =====\n");
    disp(crossRegionTable);
    fprintf("C1s R2=%.9f; F1s R2=%.9f; overall pass=%d\n", ...
        Cfit.metrics.R2,Ffit.metrics.R2,acceptance.passes);
    fprintf("No ~681.5 eV F_other component is present in this locked test.\n");
end

if showPlots
    xps.plotFitComponents(Cpre,Cfit, ...
        "Ruoff-like synthetic C 1s - reference-derived test profile");
    xps.plotFitComponents(Fpre,Ffit, ...
        "Ruoff-like synthetic F 1s - locked three-peak model");
end

report = struct("configuration",cfg,"reference",reference, ...
    "C",C,"F",F,"Cpre",Cpre,"Fpre",Fpre,"Cfit",Cfit, ...
    "Ffit",Ffit,"composition",comp,"scaling",scaling, ...
    "C1sReferenceFormulaComposition",referenceFormulaComposition, ...
    "C1sFormulaConsistency",c1sFormulaConsistencyTable, ...
    "cSyntheticTruth",cSyntheticTruth, ...
    "fSyntheticTruth",fSyntheticTruth,"C1sRecovery",cTable, ...
    "F1sRecovery",fTable,"crossRegionRecovery",crossRegionTable, ...
    "acceptance",acceptance);
end

function T = makeC1sFormulaConsistencyTable(composition,reference)
direct = reference.direct_references.overall_sample_A;
directFAtPct = direct.fluorine_atomic_percent;

quantityClass = ["DirectRuoffReference"; ...
    "ModelAppliedToRuoffPublishedFractions"; ...
    "ModelAppliedToRuoffPublishedFractions"];
candidateOrReference = ["RuoffSampleA";"WeightedC1s";"LegacyC1s"];
alpha = [NaN;composition.weighted.alpha;NaN];
fOverC = [NaN;composition.weighted.F_over_C; ...
    composition.legacy.F_over_C];
fAtPct = [directFAtPct;composition.weighted.F_atpct; ...
    composition.legacy.F_atpct];
cOverF = [NaN;composition.weighted.C_over_F; ...
    composition.legacy.C_over_F];
cxF = [string(direct.qualitative_stoichiometry); ...
    string(composition.weighted.CxF);string(composition.legacy.CxF)];
differenceFrom32AtPct = fAtPct-directFAtPct;

T = table(quantityClass,candidateOrReference,alpha,fOverC,fAtPct, ...
    cOverF,cxF,differenceFrom32AtPct, ...
    'VariableNames', {'QuantityClass','CandidateOrReference','Alpha', ...
    'F_over_C','F_atpct','C_over_F','CxF', ...
    'DifferenceFrom32atpct_pp'});
end

function T = makeCrossRegionTable(labels,trueFC,retrievedFC)
trueCx = 1./trueFC;
retrievedCx = 1./retrievedFC;
T = table(labels,trueFC,retrievedFC, ...
    100*relativeError(retrievedFC,trueFC),trueCx,retrievedCx, ...
    100*relativeError(retrievedCx,trueCx), ...
    compose("C%.3gF",trueCx),compose("C%.3gF",retrievedCx), ...
    'VariableNames', {'Quantity','SyntheticTruth_F_over_C', ...
    'Retrieved_F_over_C','F_over_C_RelativeError_pct', ...
    'SyntheticTruth_C_over_F','Retrieved_C_over_F', ...
    'C_over_F_RelativeError_pct','SyntheticTruth_CxF','Retrieved_CxF'});
end

function y = syntheticGaussianSum(energy,truth)
y = zeros(size(energy));
for i = 1:size(truth,1)
    sigma = truth(i,3)/(2*sqrt(2*log(2)));
    y = y + truth(i,2)/(sigma*sqrt(2*pi)) .* ...
        exp(-0.5*((energy-truth(i,1))/sigma).^2);
end
end

function values = relativeError(actual,expected)
values = abs(actual-expected)./expected;
end

function values = asStructArray(values)
if iscell(values),values = [values{:}];end
end

function peak = indexedPeak(peaks,index)
if iscell(peaks)
    peak = peaks{index};
else
    peak = peaks(index);
end
end

function deleteIfPresent(files)
for i = 1:numel(files)
    if isfile(files{i}),delete(files{i});end
end
end
